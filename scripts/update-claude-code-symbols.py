#!/usr/bin/env python3
"""Regenerate the Claude Code mod's symbol table from unikodo-core.

    scripts/update-claude-code-symbols.py

The mod runs inside Claude Code with no LSP server to ask, so it carries the
database itself: this dumps it with the `dump_json` example (the same source
the web frontend uses) and writes `editors/claude-code/hooks/symbols.ts`. Run it
after changing a scheme's table; CI fails while the committed file is stale.
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "editors", "claude-code", "hooks", "symbols.ts")

dump = json.loads(
    subprocess.run(
        ["cargo", "run", "-q", "-p", "unikodo-core", "--example", "dump_json"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
)

# Every scheme, in the core's order. `unicode` is dynamic (any code point), so
# its table is empty and the mod computes its one row.
schemes = dump["schemes"]
rows = {s["id"]: [] for s in schemes}
for s in dump["symbols"]:
    row = [s["name"], s["value"], s["description"] or ""]
    if s["ascii"]:
        row.append(1)
    rows[s["scheme"]].append(row)
for table in rows.values():
    # The LSP's sortText order (shorter names, then alphabetical), so a lookup
    # only has to lift an exact match and merge schemes.
    table.sort(key=lambda r: (len(r[0]), r[0]))

def js(value):
    return json.dumps(value, ensure_ascii=False)

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/update-claude-code-symbols.py from unikodo-core's\n")
    f.write("// dump_json example. Do not edit by hand: change the scheme's table and rerun.\n\n")
    f.write("/** A naming scheme: its id, display name and default trigger. */\n")
    f.write("export type Scheme = { readonly id: string; readonly display: string; readonly trigger: string }\n\n")
    f.write("/** One name: [name, value, description], with a trailing 1 when the value is a\n")
    f.write(" * single ASCII character (offered only with includeAscii). */\n")
    f.write("export type Row = readonly [string, string, string, 1?]\n\n")
    f.write("export const SCHEMES: readonly Scheme[] = [\n")
    for s in schemes:
        f.write(f"  {{ id: {js(s['id'])}, display: {js(s['display'])}, trigger: {js(s['defaultTrigger'])} }},\n")
    f.write("]\n\n")
    f.write("/** Each scheme's names, shorter first, then alphabetical. */\n")
    f.write("export const TABLES: Readonly<Record<string, readonly Row[]>> = {\n")
    for s in schemes:
        f.write(f"  {js(s['id'])}: [\n")
        for row in rows[s["id"]]:
            f.write(f"    {js(row)},\n")
        f.write("  ],\n")
    f.write("}\n")

print(f"{sum(map(len, rows.values()))} symbols -> {os.path.relpath(OUT, ROOT)}")
